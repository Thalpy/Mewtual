#[test]
fn foreign_stage_labels_and_successor_generation_never_authorize_first_initialization() {
    for field in 0..7 {
        let mut rng = ChaCha20Rng::seed_from_u64(0xd136 + field);
        let fixture = Staged::new(0xd136 + field, &mut rng);
        let store = fixture.reopen(&mut rng);
        let changed = fixture.rewrite(&store, &mut rng, |plain| {
            let mut decoder = Decoder::new(plain);
            decoder.get_str().unwrap();
            let mut offset = 0;
            let mut revision_at = 0;
            for index in 0..5 {
                let label = decoder.get_bytes().unwrap();
                if field == index {
                    offset = label.as_ptr() as usize - plain.as_ptr() as usize;
                }
                if index == 4 {
                    revision_at = label.as_ptr() as usize + label.len() - plain.as_ptr() as usize;
                }
            }
            // Both revisions/generations are fixed-width u64 immediately after the nonce.
            if field == 5 {
                offset = revision_at + 7;
            }
            if field == 6 {
                offset = revision_at + 15;
            }
            if field == 6 {
                plain[offset] = 2; // explicit successor generation, not 1 XOR 1 -> 0
            } else {
                plain[offset] ^= 1;
            }
        });
        let classification = store.prepare_owner_evidence_restore(&fixture.group, fixture.signer);
        // A foreign nonce is conservatively retained as offline old-lineage evidence; it can
        // never expose transport/private MLS. Every other mismatch refuses source preparation.
        match classification {
            Err(_) => {}
            Ok(OwnerRestoreClassification::Retired(offline)) => drop(offline),
            other => panic!("foreign stage exposed a positive preparation: {other:?}"),
        }
        assert_eq!(fs::read(&fixture.stage).unwrap(), changed);
        assert!(!fixture.canonical.exists());
        assert!(matches!(
            fixture.resolve(&store),
            ChatAdmissionResolution::Initializing(_)
        ));
        assert_eq!(store.owner_evidence.canonical.lock().unwrap().hot_bytes, 0);
    }
}
