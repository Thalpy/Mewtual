    let fixture = Staged::new(0xd143, &mut rng);
    let store = ServerStore::open(fixture.directory.path(), SECRET, &mut rng).unwrap();
    store
        .configure_owner_evidence_budget(
            OwnerEvidenceBudget::checkpoint(
                4,
                16 * 1024 * 1024,
                16 * 1024 * 1024,
                1024 * 1024,
                512 * 1024,
                512 * 1024,
            )
            .unwrap(),
        )
        .unwrap();
    // Both are real opaque reads of the original Initializing stage before any promotion.
    let mut first = decode(fixture.prepare(&store), &store, 0xd144);
    let mut duplicate = decode(fixture.prepare(&store), &store, 0xd145);
