#[test]
fn original_negative_revocation_fences_both_sides_of_actual_stage_filesystem_admission() {
    use std::sync::mpsc::{channel, Sender};
    use std::time::Duration;
    // Harness deadlines only, not protocol timers. Ordinary channels plus this guard release
    // the worker on assertion unwind; join occurs only after its bounded completion signal.
    struct ReleaseOnDrop(Option<Sender<()>>);
    impl Drop for ReleaseOnDrop {
        fn drop(&mut self) {
            if let Some(sender) = self.0.take() {
                let _ = sender.send(());
            }
        }
    }
    for admitted in [false, true] {
        let mut rng = ChaCha20Rng::seed_from_u64(0xd121 + u64::from(admitted));
        let fixture = Staged::new(0xd121, &mut rng);
        let store = Arc::new(fixture.reopen(&mut rng));
        let mut restore = decode(fixture.prepare(&store), &store, 0xd122);
        let ChatAdmissionResolution::Initializing(preparation) = fixture.resolve(&store) else {
            panic!("Initializing");
        };
        let (reached_tx, reached_rx) = channel();
        let (release_tx, release_rx) = channel();
        let (done_tx, done_rx) = channel();
        let release = ReleaseOnDrop(Some(release_tx));
        let hook = Some(Box::new(move || {
            reached_tx.send(()).unwrap();
            release_rx.recv_timeout(Duration::from_secs(10)).unwrap();
        }) as Box<dyn FnOnce() + Send>);
        if admitted {
            *store
                .owner_evidence
                .after_owner_stage_admission
                .lock()
                .unwrap() = hook;
        } else {
            *store
                .owner_evidence
                .before_owner_stage_admission
                .lock()
                .unwrap() = hook;
        }
        let worker_store = store.clone();
        let worker = std::thread::spawn(move || {
            let refused = restore
                .retry(&worker_store, &mut ChaCha20Rng::seed_from_u64(0xd123))
                .is_err();
            drop(restore); // release original read fee outside either writer
            let _ = done_tx.send(refused);
        });
        reached_rx.recv_timeout(Duration::from_secs(10)).unwrap();
        assert_eq!(fixture.canonical.exists(), admitted);
        assert_eq!(fixture.stage.exists(), !admitted);
        // This negative handle acquires neither held writer. The final pre-move check must
        // refuse it in the first ordering; the second must retain the already moved original.
        preparation.revoker().revoke();
        let (retiring_tx, retiring_rx) = channel();
        let (retired_tx, retired_rx) = channel();
        store
            .chat_mount
            .observe_next_writer_contention(move |blocked| {
                let _ = retiring_tx.send(blocked);
            });
        let retiring_store = store.clone();
        let retirement = std::thread::spawn(move || {
            let result = retiring_store
                .retire_chat_preparation(&preparation, &mut ChaCha20Rng::seed_from_u64(0xd130));
            let _ = retired_tx.send(result.is_ok());
        });
        assert!(
            retiring_rx.recv_timeout(Duration::from_secs(10)).unwrap(),
            "retirement must contend on the actual admission writer held through filesystem work"
        );
        assert!(
            matches!(
                retired_rx.try_recv(),
                Err(std::sync::mpsc::TryRecvError::Empty)
            ),
            "retirement cannot report completion while admitted work is still held"
        );
        drop(release);
        assert!(done_rx.recv_timeout(Duration::from_secs(10)).unwrap());
        worker.join().unwrap();
        assert!(retired_rx.recv_timeout(Duration::from_secs(10)).unwrap());
        retirement.join().unwrap();
        assert!(matches!(
            fixture.resolve(&store),
            ChatAdmissionResolution::Retired
        ));
        assert_eq!(
            fs::read(if admitted {
                &fixture.canonical
            } else {
                &fixture.stage
            })
            .unwrap(),
            fixture.raw
        );
        assert_eq!(fixture.canonical.exists(), admitted);
        assert_eq!(fixture.stage.exists(), !admitted);
        assert_eq!(store.owner_evidence.canonical.lock().unwrap().hot_bytes, 0);
    }
}

