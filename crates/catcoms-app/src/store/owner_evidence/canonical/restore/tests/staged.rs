    assert!(duplicate.saved.is_some());
    assert_eq!(fs::read(&fixture.canonical).unwrap(), fixture.raw);
    assert!(!fixture.stage.exists());
    assert_eq!(store.owner_evidence.canonical.lock().unwrap().hot_bytes, 0);
